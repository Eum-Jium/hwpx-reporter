def fit(slots, label, want=2):
    hits = []
    for combo in itertools.product(*slots):
        s = "".join(combo)
        if check_line_lengths(s):
            continue
        parts = break_points(s)
        if len(parts) != want or not all(k for _, k in parts[:-1]):
            continue
        hits.append(s)
    print(f"== {label}: {len(hits)}건")
    for s in hits[:2]:
        print(f"   {len(s)}자 | {s}")
    return hits


