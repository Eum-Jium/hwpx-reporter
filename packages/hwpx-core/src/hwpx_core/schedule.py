# -*- coding: utf-8 -*-
"""일정 줄 날짜의 자릿수 맞춤 — 탭 정렬은 앞 열의 **폭**이 같아야 선다.

`◦ ’26. 9.\t: 표준 모델 설계` 처럼 한 자리 월을 쓰면 날짜가 두 자리짜리보다
한 글자 좁아 **앞쪽 탭 스톱**에 멈춘다. 그러면 뒤 내용이 날짜에 바짝 붙어
(콜론이 날짜에 달라붙은 것처럼 보인다) 여러 줄의 열이 어긋난다.

휴먼명조 15pt 에서 숫자와 공백의 advance 는 **둘 다 5.27pt** 로 같다
(`tools/verify/linebreak.py` 실측 상수). 그래서 빠진 한 자리를 공백 하나로
메우면 `’26.  9.` 와 `’26. 10.` 의 폭이 정확히 같아져 같은 탭 스톱에 선다.

**stdlib 만 쓴다** — markers.py·gaps.py 와 같은 이유(모드 B 가 파일째 적재한다).
"""
import re

# ". " 뒤에 오는 한 자리 수 = 월 또는 일. 뒤는 마침표·여는 괄호·공백·끝.
# 이미 메워진 `. ` + ` 9` 는 앞이 두 칸이라 다시 걸리지 않는다(멱등).
_ONE_DIGIT = re.compile(r"(?<=\. )(\d)(?=[.(\s]|$)")


def pad_tab_date(text: str) -> str:
    """탭 앞 날짜의 한 자리 월·일을 공백으로 메워 두 자리 폭에 맞춘다.

    탭이 없는 줄은 그대로 둔다 — 정렬할 열이 없으면 폭을 맞출 이유도 없고,
    본문 문장의 `’26. 9. 준공` 같은 표현까지 건드릴 이유는 더더욱 없다.
    """
    if not text or "\t" not in text:
        return text
    head, sep, rest = text.partition("\t")
    return _ONE_DIGIT.sub(r" \1", head) + sep + rest
